// Release signing is read from keystore.properties (never committed). Without it the
// release build is simply left unsigned.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.diary.petcare"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.diary.petcare"
        minSdk = 24
        targetSdk = 37
        versionCode = 1
        versionName = "1.0.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables { useSupportLibrary = true }
    }

    signingConfigs {
        if (keystoreProps.getProperty("storeFile") != null) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfigs.findByName("release")?.let { signingConfig = it }
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    androidResources {
        // v1 ships English only. Urdu strings stay in values-ur; add "ur" back for v2.
        localeFilters += listOf("en")
    }

    // v2: reminder notifications live in src/v2/java and are not compiled in v1.
    // Un-comment this (and the work-runtime-ktx dependency) to bring them back.
    // See app/src/v2/README.md.
    // sourceSets["main"].java.srcDir("src/v2/java")

    buildFeatures {
        compose = true
        buildConfig = true
    }
}

